// Поддерживаются заглавные латинские буквы, цифры, пробел и немного пунктуации.
// Неизвестные символы заменяются на "?".

const (
	glyphWidth  = 5
	glyphHeight = 7
)

// glyph - маска символа: по одному биту на пиксель в каждой из 7 строк,
// младшие 5 бит строки соответствуют 5 столбцам символа (слева направо).
type glyph [glyphHeight]byte

// makeGlyph превращает набор строк вида ".###." в маску глифа.
// Символ '#' - закрашенный пиксель, любой другой символ - пустой.
func makeGlyph(rows ...string) glyph {
	var g glyph
	for i := 0; i < glyphHeight && i < len(rows); i++ {
		row := rows[i]
		var b byte
		for col := 0; col < glyphWidth; col++ {
			b <<= 1
			if col < len(row) && row[col] == '#' {
				b |= 1
			}
		}
		g[i] = b
	}
	return g
}

